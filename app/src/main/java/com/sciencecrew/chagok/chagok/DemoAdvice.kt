package com.sciencecrew.chagok.chagok

/**
 * 시연용 예시 답변.
 * 글레오(기기 안 LLM)가 응답하지 않을 때만 쓰며, 화면에 "시연용 예시 답변"이라고 반드시 표시한다.
 * 실제 AI 응답이 아니라 메모에 들어 있는 단어에 맞춰 미리 써 둔 안내문이다.
 */
object DemoAdvice {

    private val rules: List<Pair<Regex, String>> = listOf(
        Regex("펑크|공기압|타이어|바퀴") to
            "출발 전에 타이어가 눈에 띄게 주저앉았는지 먼저 확인해 주세요. 공기압 경고만 켜졌다면 가까운 정비소에서 공기압 점검을 받으시면 돼요. 펑크가 확실하면 운행하지 말고 긴급출동 서비스를 불러 주세요.",
        Regex("브레이크|제동") to
            "브레이크 이상은 안전과 직결돼요. 운행을 미루고 정비소에서 먼저 점검을 받아 주세요.",
        Regex("엔진오일|오일|엔진") to
            "계기판에 엔진 관련 경고가 있는지 확인해 주세요. 경고가 켜져 있다면 무리하게 운행하지 말고 가까운 정비소에 점검을 예약해 주세요.",
        Regex("경고등|경고|불이 들어") to
            "어떤 경고등인지 계기판에서 먼저 확인해 주세요. 빨간색이면 운행을 멈추고 점검을 받는 게 안전하고, 노란색이면 가까운 정비소에 점검을 예약해 주세요.",
        Regex("배터리|충전|방전") to
            "출발 전에 남은 배터리와 주행 가능 거리를 확인해 주세요. 목적지까지 부족하면 내비에서 경로상 충전소를 먼저 찾아 두시는 게 좋아요.",
        Regex("기름|주유|연료") to
            "출발 전에 남은 연료와 주행 가능 거리를 확인해 주세요. 부족하면 경로상 주유소를 먼저 들르시는 게 좋아요.",
        Regex("사고|긁|찌그러|흠집|파손|부딪") to
            "차량 외관을 출발 전에 한 번 둘러봐 주세요. 사진을 남겨 두고, 수리가 필요하면 보험사나 정비소에 접수해 주세요.",
        Regex("두고|놓고|분실|챙겨|우산|지갑|가방") to
            "차 안에 두고 내린 물건이 있다고 해요. 출발 전에 뒷좌석과 트렁크를 한 번 확인해 주세요.",
        Regex("세차|더러|청소|냄새") to
            "차량 실내나 외관 관리가 필요해 보여요. 가까운 세차장에 들르시거나 다음 주차 때 정리해 주세요.",
    )

    private const val DEFAULT =
        "남기신 내용을 출발 전에 한 번 확인해 주세요. 차량 점검이 필요해 보이면 가까운 정비소에 예약하실 수 있어요."

    fun forNote(text: String): String = rules.firstOrNull { it.first.containsMatchIn(text) }?.second ?: DEFAULT
}
